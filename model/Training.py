# -----------------------------------------------------------------------------
# Logging & Reproducibility
# -----------------------------------------------------------------------------
def setup_logging(rank: int = 0) -> None:
    """
    
    Args:
        rank (int): Process rank in distributed setup (0 = master process)
    
    Log Levels:
        - INFO: Training progress, validation metrics, checkpoint events
        - WARNING: Non-critical issues (e.g., empty batches)
        - ERROR: Critical failures requiring intervention
    
    Output:
        - Console: All ranks log to stdout with [RANK] prefix for traceability
        - File: Master rank (0) additionally logs to training.log
    
    """
    log_format = f'%(asctime)s [%(levelname)s] [RANK {rank}] %(message)s'
    handlers = [logging.StreamHandler(sys.stdout)]
    
    if rank == 0:
        handlers.append(logging.FileHandler('training.log', mode='w'))
    
    logging.basicConfig(
        level=logging.INFO,
        format=log_format,
        datefmt='%Y-%m-%d %H:%M:%S',
        handlers=handlers
    )


def set_seed(seed: int, rank: int = 0) -> None:
    """
    Sets deterministic random seeds across all libraries for reproducible training.
    
    Args:
        seed (int): Base random seed value
        rank (int): Process rank (used to derive rank-specific seeds to avoid correlation)
    
    Seed Derivation Strategy:
        - Global seed: base_seed + rank × 1000
        - Ensures different but deterministic sequences across GPUs
        - Prevents identical augmentation patterns across devices
    
    Libraries Seeded:
        - Python random
        - NumPy
        - PyTorch (CPU and CUDA)
        - CuDNN (with deterministic mode enabled)
    

    """
    seed_with_rank = seed + rank * 1000
    random.seed(seed_with_rank)
    np.random.seed(seed_with_rank)
    torch.manual_seed(seed_with_rank)
    if torch.cuda.is_available():
        torch.cuda.manual_seed(seed_with_rank)
        torch.cuda.manual_seed_all(seed_with_rank)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False


